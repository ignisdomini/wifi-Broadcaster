/** Целочисленные настройки — чтобы не приводить типы в каждом месте. */
function setting_int_keys(): array
{
    return [
        'max_text_chars', 'broadcast_max_bytes',
        'rate_limit_per_hour', 'moderation', 'retention_days',
    ];
}

function all_settings(bool $refresh = false): array
{
    static $cache = null;

    if ($cache === null || $refresh) {
        $cache = setting_defaults();
        try {
            foreach (db_all('SELECT k, v FROM settings') as $row) {
                if (array_key_exists($row['k'], $cache)) {
                    $cache[$row['k']] = $row['v'];
                }
            }
        } catch (Throwable $e) {
            // База ещё не готова (установка) — работаем на значениях по умолчанию.
        }
        foreach (setting_int_keys() as $key) {
            $cache[$key] = (int)$cache[$key];
        }
    }

    return $cache;
}

function setting(string $key, mixed $default = null): mixed
{
    $all = all_settings();
    return $all[$key] ?? $default;
}

function setting_int(string $key): int
{
    return (int)setting($key, 0);
}

function save_settings(array $values): void
{
    $allowed = setting_defaults();
    $stmt = db()->prepare(
        'INSERT INTO settings (k, v) VALUES (?, ?) ON DUPLICATE KEY UPDATE v = VALUES(v)'
    );
    foreach ($values as $key => $value) {
        if (!array_key_exists($key, $allowed)) {
            continue;
        }
        $stmt->execute([$key, (string)$value]);
    }
    all_settings(true);
}

/**
 * Лимиты в том виде, в каком их получает приложение.
 * Отдельная функция, чтобы API и админка не разъезжались.
 */
