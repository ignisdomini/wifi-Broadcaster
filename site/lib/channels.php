<?php
declare(strict_types=1);

/**
 * Каналы радиоинформатора.
 *
 * Настоящую радиочастоту у Wi-Fi Direct задать нельзя — обнаружение служб
 * живёт на социальных каналах 1/6/11 и переключать их приложению не дают.
 * Поэтому канал здесь логический: номер едет в TXT-записи, а приёмник
 * отбрасывает всё, что пришло не на его канале.
 *
 * У каналов есть темы, и это не украшение. Без них рынок, поход и объявление
 * о пропавшей собаке валятся в одну кучу, а с ними человек настраивается на
 * то, ради чего пришёл: продавец слушает торговлю, турист — маршруты, а
 * тревожный канал остаётся тихим до того дня, когда он понадобится.
 *
 * Первый канал общий: на нём слышно всех, и приложение работает без всякой
 * настройки. Последние оставлены свободными — под то, чего мы не предусмотрели.
 */

const EFIR_CHANNEL_MIN = 1;
const EFIR_CHANNEL_MAX = 16;

/** Канал по умолчанию: на нём все слышат друг друга. */
const EFIR_CHANNEL_DEFAULT = 1;

/**
 * Темы каналов.
 *
 * @return array<int, array{channel:int, title:string, hint:string}>
 */
function channel_themes(): array
{
    $themes = [
        1  => ['Общий', 'Слышно всех, кто рядом. Сюда попадают по умолчанию.'],
        2  => ['Еда и кафе', 'Меню дня, что осталось к вечеру, когда открыто.'],
        3  => ['Скидки и промокоды', 'Коды, которые действуют, пока вы в двух шагах.'],
        4  => ['Рынок и торговля', 'Что привезли, почём, у какого прилавка.'],
        5  => ['Туризм и походы', 'Стоянки, броды, погода на тропе, кто где идёт.'],
        6  => ['Тревога', 'Помощь, пропажи, опасность. Держите включённым в беде.'],
        7  => ['Объявления', 'Личное: продам, отдам, ищу, подвезу.'],
        8  => ['Знакомства', 'Кто рядом и не против познакомиться.'],
        9  => ['Сообщества', 'Клубы, кружки, встречи по интересам.'],
        10 => ['События', 'Концерт во дворе, лекция, распродажа через час.'],
        11 => ['Транспорт', 'Попутчики, места в машине, что со стоянкой.'],
        12 => ['Работа', 'Руки нужны здесь и сейчас.'],
    ];

    $out = [];
    for ($i = EFIR_CHANNEL_MIN; $i <= EFIR_CHANNEL_MAX; $i++) {
        [$title, $hint] = $themes[$i] ?? ['Свободный ' . $i, 'Тема не занята — договоритесь на месте.'];
        $out[] = ['channel' => $i, 'title' => $title, 'hint' => $hint];
    }
    return $out;
}

function normalize_channel(mixed $value): int
{
    $channel = (int)$value;
    if ($channel < EFIR_CHANNEL_MIN || $channel > EFIR_CHANNEL_MAX) {
        return EFIR_CHANNEL_DEFAULT;
    }
    return $channel;
}

function channel_title(int $channel): string
{
    $channel = normalize_channel($channel);
    foreach (channel_themes() as $theme) {
        if ($theme['channel'] === $channel) {
            return $theme['title'];
        }
    }
    return 'Канал ' . $channel;
}

/** @return array<int, array{channel:int, title:string, hint:string}> */
function all_channels(): array
{
    return channel_themes();
}
